// Writes the Jukebox Fountain's style file for the renderer from the bench: the shipped look's values (bench/standard-tune6.json,
// "Your tune #6"; another frozen spec - standard-t8.json, the earlier T8 reference - can be passed instead) and the bench's own shaders, lifted as they are - only their WebGL header becomes a desktop
// GL 3.3 one and the template slots are filled. The renderer builds nothing of its own, so it draws what the bench draws.
//   node export_t8.mjs [spec.json]   -> native/visualizer/presets/UPS - Jukebox Fountain.vis
// Format: "P NAME value" per parameter (the shaders' uP[] order), "U name v..." uniforms, "I name v" int uniforms, then
// the three shaders, each after a "@@SCENE" / "@@BLUR" / "@@COMP" line.
import fs from "fs";
const root = "C:/Projects/UniPSound/UniPlaySong/native/visualizer";
const html = fs.readFileSync(`${root}/bench/fountain-bench.html`, "utf8").split("\r\n").join("\n");
const specFile = process.argv[2] || "standard-tune6.json";
const spec = JSON.parse(fs.readFileSync(`${root}/bench/${specFile}`, "utf8"));

// the parameters, in the bench's PARAMS order (the order of uP[] in its shaders)
const block = html.slice(html.indexOf("const PARAMS = ["), html.indexOf("\n];", html.indexOf("const PARAMS = [")));
const names = [...block.matchAll(/^  \["([A-Z0-9_]+)", "/gm)].map(m => m[1]);
for (const n of names) if (!(n in spec.params)) throw new Error(specFile + " has no " + n);
const HIST = 128;

const template = name => {
  const a = html.indexOf(`const ${name} = \``), b = html.indexOf("`;", a);
  if (a < 0 || b < 0) throw new Error("no " + name);
  return html.slice(a + `const ${name} = \``.length, b);
};
const defs = names.map((n, i) => `#define ${n} uP[${i}]`).join("\n");
const port = src => {
  if (!src.startsWith("#version 300 es\nprecision highp float;\n")) throw new Error("unexpected shader header");
  src = "#version 330 core\n" + src.slice("#version 300 es\nprecision highp float;\n".length);
  src = src.split("${PARAMS.length}").join(String(names.length)).split("${DEFS}").join(defs).split("${HIST - 1}").join(String(HIST - 1));
  if (src.includes("${")) throw new Error("unfilled template slot: " + src.slice(src.indexOf("${"), src.indexOf("${") + 30));
  return src;
};
let comp = port(template("COMP_FS"));
// the page keys the picture over its own background and draws a cover disc; the renderer's key pass makes the same
// key (coverage = the brightest channel) and the theme draws the cover - so the composite ends at the keyed colour
const keyAt = comp.indexOf("  // luma key over the background, as the page shows the visualizer");
const endAt = comp.indexOf("  outColor = vec4(clamp(outc, 0.0, 1.0), 1.0);\n}");
if (keyAt < 0 || endAt < 0) throw new Error("composite ending changed - update export_t8.mjs");
comp = comp.slice(0, keyAt) + "  outColor = vec4(col, 1.0);\n}";

// the colours: the palette's two ends and its scheme, as the bench sets them each frame
const s = spec.scheme, pl = spec.palette, hot = s.hot === 2 ? pl.high : pl.low, hm = Math.max(...hot);
const v3 = a => a.map(x => +x.toFixed(6)).join(" ");
const out = [
  `# UniPlaySong visualizer - Jukebox Fountain. Generated by native/visualizer/bench/tools/export_t8.mjs`,
  `# from bench/${specFile} and bench/fountain-bench.html - edit those and regenerate, not this file.`,
  ...names.map(n => `P ${n} ${spec.params[n]}`),
  `U uColMin ${v3(pl.low)}`, `U uColMax ${v3(pl.high)}`, `U uColMid ${v3(s.mid || [-1, -1, -1])}`,
  `U uCoolA ${v3(s.cool[0])}`, `U uCoolB ${v3(s.cool[1])}`, `U uKick ${v3(s.kick)}`,
  `U uCalmA ${v3(s.calm[0])}`, `U uCalmB ${v3(s.calm[1])}`, `U uGlint ${v3(s.glint)}`,
  `U uHotMax ${s.hot === 2 ? 1 : 0}`, `U uHeatGain ${s.heatGain}`, `U uCoolGain ${s.coolGain}`, `U uSplit ${s.split}`,
  `U uGlowHot ${v3(hot.map(x => x / hm))}`, `U uBloomTint ${v3(s.bloom)}`,
  `I uGrad ${["random", "across", "core-to-tips", "spectrum", "left-to-right"].indexOf(spec.params.GRADIENT)}`,
  "@@SCENE", port(template("SCENE_FS")),
  "@@BLUR", port(template("BLUR_FS")),
  "@@COMP", comp, ""];
const dest = `${root}/presets/UPS - Jukebox Fountain.vis`;
fs.writeFileSync(dest, out.join("\n"));
console.log(`wrote ${dest}: ${names.length} params`);
